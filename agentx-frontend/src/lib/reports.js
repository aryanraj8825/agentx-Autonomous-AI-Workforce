/** Builds the demo deliverables. Figures are illustrative placeholders, not real data. */
export function buildCsv(task) {
  const rows = [['rank', 'company', 'segment', 'business_model', 'funding_usd_m (illustrative)', 'confidence']];
  const seg = ['Enterprise automation', 'Vertical AI', 'Developer tools', 'Conversational AI', 'Computer vision'];
  const models = ['Subscription', 'Usage-based', 'Seat-based', 'Licensing'];
  for (let i = 1; i <= 10; i++) {
    rows.push([i, `Company ${String(i).padStart(2, '0')}`, seg[i % seg.length], models[i % models.length], (120 - i * 9).toFixed(0), (0.95 - i * 0.03).toFixed(2)]);
  }
  return rows.map((r) => r.join(',')).join('\n');
}

export function buildReport(task) {
  return `# ${task.title}

> Demo output generated by the AgentX simulation. Figures and company names are placeholders until the backend is connected.

## Executive summary
The market shows concentrated funding, fast movement toward vertical products and a clear split between usage-based and seat-based pricing. Five insights are detailed below.

## Objective
${task.prompt}

## Method
1. Supervisor interpreted the goal and selected six agents.
2. Planner produced a nine-step dependency graph; two research steps ran in parallel.
3. Researcher collected facts from 25 sources and kept a citation for each claim.
4. Analyst compared entities and produced charts in a sandbox.
5. Writer drafted this report; Reviewer returned it once for a missing citation.

## Key findings
- Segment growth is concentrated in enterprise automation [E1]
- Most leaders sell usage-based or seat-based subscriptions [E2]
- Funding is skewed toward the top three companies [E3]
- Vertical products outpace horizontal tools in retention [E4]
- Regional language support is an emerging differentiator [E5]

## Limitations
Public pricing is available for only some vendors [E6], so pricing comparisons carry lower confidence.

## Sources
${(task.evidence || []).map((e) => `- [${e.id}] ${e.source} (confidence ${e.confidence.toFixed(2)})`).join('\n')}
`;
}

export function printableHtml(task) {
  const md = buildReport(task)
    .replace(/^# (.*)$/gm, '<h1>$1</h1>')
    .replace(/^## (.*)$/gm, '<h2>$1</h2>')
    .replace(/^> (.*)$/gm, '<blockquote>$1</blockquote>')
    .replace(/^- (.*)$/gm, '<li>$1</li>')
    .replace(/^\d\. (.*)$/gm, '<li>$1</li>')
    .replace(/\n\n/g, '\n');
  return `<!doctype html><meta charset="utf-8"><title>${task.title}</title>
<style>body{font:15px/1.6 Georgia,serif;max-width:720px;margin:48px auto;color:#14171e}h1{font:700 28px system-ui}h2{font:600 18px system-ui;margin-top:28px}blockquote{border-left:3px solid #84cc16;margin:16px 0;padding:4px 14px;color:#555}li{margin:4px 0}</style>
${md}<script>window.onload=()=>setTimeout(()=>window.print(),300)</script>`;
}
